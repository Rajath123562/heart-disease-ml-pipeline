/**
 * Generate synthetic demo dataset (300 rows) with realistic correlations
 */
export function generateSyntheticDataset(seed: number = 42): string {
  let currentSeed = seed;
  function pseudoRandom(): number {
    currentSeed = (currentSeed * 9301 + 49297) % 233280;
    return currentSeed / 233280;
  }

  function randRange(min: number, max: number): number {
    return min + pseudoRandom() * (max - min);
  }

  const rows: string[] = ['age,sex,cp,trestbps,chol,fbs,restecg,thalach,exang,oldpeak,slope,ca,thal,target'];

  for (let i = 0; i < 300; i++) {
    const age = Math.round(randRange(32, 75));
    const sex = pseudoRandom() > 0.32 ? 1 : 0;
    
    // Latent disease probability based on medical risk factors
    let risk = -1.2;
    risk += (age - 54) * 0.04;
    risk += sex * 0.45;
    
    // Chest pain: higher cp (typical 0 in heart.csv, or atypical 1, non-anginal 2, asymptomatic 3)
    const cpRoll = pseudoRandom();
    let cp = 0;
    if (cpRoll < 0.48) cp = 0;
    else if (cpRoll < 0.68) cp = 1;
    else if (cpRoll < 0.88) cp = 2;
    else cp = 3;
    if (cp > 0) risk += 0.85;

    const trestbps = Math.round(randRange(100, 180) + (risk > 0 ? 10 : 0));
    const chol = Math.round(randRange(160, 360) + (risk > 0 ? 15 : 0));
    const fbs = pseudoRandom() < (risk > 0 ? 0.22 : 0.10) ? 1 : 0;
    const restecg = pseudoRandom() < 0.5 ? 1 : (pseudoRandom() < 0.1 ? 2 : 0);

    // Thalach: lower for diseased
    const thalach = Math.round(randRange(95, 195) - (risk > 0 ? 22 : -5));
    risk -= (thalach - 150) * 0.025;

    // Exang: exercise induced angina
    const exang = pseudoRandom() < (risk > 0 ? 0.60 : 0.18) ? 1 : 0;
    if (exang === 1) risk += 0.9;

    // Oldpeak: ST depression
    const oldpeak = Math.max(0, parseFloat((randRange(0, 3.5) + (risk > 0 ? 1.1 : -0.4)).toFixed(1)));
    risk += oldpeak * 0.7;

    const slope = oldpeak > 1.5 ? (pseudoRandom() < 0.7 ? 1 : 0) : 2;
    
    // Major vessels ca (0-3)
    const ca = pseudoRandom() < (risk > 0 ? 0.65 : 0.2) ? Math.floor(randRange(1, 4)) : 0;
    risk += ca * 0.6;

    // Thal (1: normal, 2: fixed, 3: reversible)
    const thal = pseudoRandom() < (risk > 0 ? 0.7 : 0.25) ? (pseudoRandom() < 0.8 ? 2 : 3) : 1;

    // Target binarization with sigmoid
    const prob = 1 / (1 + Math.exp(-risk));
    const target = prob > 0.48 ? 1 : 0;

    rows.push(`${age},${sex},${cp},${trestbps},${chol},${fbs},${restecg},${thalach},${exang},${oldpeak},${slope},${ca},${thal},${target}`);
  }

  return rows.join('\n');
}

